    function boot() {
        if (__skhI18nBooted) return;
        var LMS = window.SokoHaiLMS;
        if (!LMS) { setTimeout(boot, 120); return; }
        __skhI18nBooted = true;
        Object.keys(KEYS).forEach(function (k) {
            try { LMS.register(k, KEYS[k][0], KEYS[k][1], 'reviewed'); } catch (e) {}
        });
        Object.keys(KEYS2).forEach(function (k) {
            try { LMS.register(k, KEYS2[k][0], KEYS2[k][1], 'reviewed'); } catch (e) {}
        });
        // Tumia lugha kwa DOM iliyopo (nav/menu/tabs/sliders)
        try { LMS.apply(document.body); } catch (e) {}
        applyLabels();
        window.addEventListener('sokohai:languageChanged', function (e) {
            if (e && e.detail && e.detail.lang) { syncSwitch(e.detail.lang); applyLabels(); }
        });
        // Ikiwa mtumiaji alichagua lugha kabla LMS hajapakia, iheshimu sasa.
        if (window.__skhPendingLang && LMS.supported.includes(window.__skhPendingLang)) {
            window.setSokoHaiLanguage(window.__skhPendingLang);
            applyLabels();
        }
        syncSwitch(LMS.lang);
    }

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', boot);
    } else {
        boot();
    }
