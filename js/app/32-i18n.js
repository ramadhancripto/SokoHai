    function syncSwitch(lang) {
        var label = document.getElementById('langToggleLabel');
        if (label) label.textContent = (lang === 'en') ? 'EN' : 'SW';
        document.querySelectorAll('.lang-dropdown-opt').forEach(function (b) {
            var on = b.getAttribute('data-lang') === lang;
            b.classList.toggle('active', on);
            var chk = b.querySelector('.lang-check');
            if (chk) chk.style.visibility = on ? 'visible' : 'hidden';
        });
    }

    function closeLangDropdown() {
        var dd = document.getElementById('langDropdown');
        var btn = document.getElementById('langToggleBtn');
        if (dd) dd.style.display = 'none';
        if (btn) { btn.setAttribute('aria-expanded', 'false'); btn.classList.remove('open'); }
    }

    // [LUGHA 2026-09] Button moja inafungua/funga dropdown ya options.
    window.skhToggleLangDropdown = function (e) {
        if (e && e.stopPropagation) e.stopPropagation();
        var dd = document.getElementById('langDropdown');
        var btn = document.getElementById('langToggleBtn');
        if (!dd) return;
        // [R21] mobile: hamisha menu juu ya body (sticky-top stacking context haifutii bottom-nav)
        if (!dd.dataset.topLevel && window.innerWidth <= 900) { document.body.appendChild(dd); dd.dataset.topLevel = '1'; }
        var open = dd.style.display !== 'none';
        dd.style.display = open ? 'none' : 'block';
        if (btn) {
            btn.setAttribute('aria-expanded', open ? 'false' : 'true');
            btn.classList.toggle('open', !open);
        }
    };
    // Funga dropdown ukigusa sehemu nyingine yoyote.
    document.addEventListener('click', function (e) {
        var wrap = document.getElementById('langSwitchWrap');
        var dd = document.getElementById('langDropdown');
        if (dd && wrap && !wrap.contains(e.target) && !dd.contains(e.target)) closeLangDropdown();
    });
    // Funga dropdown kwa kitufe cha ESC.
    document.addEventListener('keydown', function (e) {
        if (e && e.key === 'Escape') closeLangDropdown();
    });

    // data-i18n-label / data-i18n-title (kwa optgroup/label/title attributes ambazo LMS.apply haishughulikii)
    function applyLabels() {
        document.querySelectorAll('[data-i18n-label]').forEach(function (el) {
            var key = el.getAttribute('data-i18n-label');
            if (key && window.t) el.setAttribute('label', window.t(key));
        });
        document.querySelectorAll('[data-i18n-title]').forEach(function (el) {
            var key = el.getAttribute('data-i18n-title');
            if (key && window.t) el.setAttribute('title', window.t(key));
        });
    }

    // [LUGHA 2026-09] Inafafanuliwa mara moja (sio ndani ya boot) ili swichi
    // ifanye kazi hata kabla SokoHaiLMS hajapakia kikamilifu.
    window.skhSetLang = function (lang) {
        if (lang !== 'sw' && lang !== 'en') lang = 'sw';
        window.__skhPendingLang = lang;
        var LMS = window.SokoHaiLMS;
        if (LMS) {
            window.setSokoHaiLanguage(lang);
            applyLabels();
            syncSwitch(lang);
        } else {
            // LMS bado hajapakia: hifadhi chaguo na rekebisha label moja kwa moja.
            try { skh.localStorage.setItem('sokohai_language', lang); } catch (e) {}
            syncSwitch(lang);
        }
        closeLangDropdown();
    };


