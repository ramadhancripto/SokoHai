#!/usr/bin/env node
/* [2026-11-06] Stage 6 — connect the owner's taxonomy source (01–44) to the runtime.
 *
 * Generates shared/canonical-taxonomy-owner-branches.js (data-only, CommonJS) with
 * product types + attributes for every source section whose name matches an EXISTING
 * runtime sub-category (shared/canonical-taxonomy-data.js PRODUCT_SUBCATEGORIES).
 * Only exact (normalised) name matches are used, so no new sub-category is invented and
 * no existing id changes; canonical-taxonomy-data.js merges these additively.
 *
 * Usage: node tools/build_owner_taxonomy_branches.mjs [--check]
 */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { parseSource, norm } from './taxonomy_source_reconcile.mjs';

const require = createRequire(import.meta.url);
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const SRC = path.join(ROOT, 'docs/taxonomy-source/SOKOHAI-TAXONOMY-01-44-OWNER-SOURCE-2026-11-06.txt');
const OUT = path.join(ROOT, 'shared/canonical-taxonomy-owner-branches.js');

// Read sub-category names WITHOUT the merge (avoid a require cycle on regeneration).
process.env.SKH_TAXONOMY_SKIP_OWNER_BRANCHES = '1';
const data = require('../shared/canonical-taxonomy-data.js');

// Owner wording that differs from the runtime sub-category label (same branch).
const ALIASES = {
  'CAT-01': { 'Sweets, Snacks & Confectionery': 'Snacks & Sweets', 'Traditional / Local Foods': 'Local & Traditional Foods',
    'Mizizi, Viazi & Tubers': 'Mizizi & Viazi', 'Mboga & Mazao Fresh': 'Mboga & Fresh Produce' }
};
// Whole-word prefix match ("Viungo" ~ "Viungo & Seasonings", "STORAGE" ~ "Storage Devices").
function resolve(cid, name, subs, byNorm) {
  if (ALIASES[cid] && ALIASES[cid][name]) return ALIASES[cid][name];
  const n = norm(name);
  if (byNorm.has(n)) return byNorm.get(n);
  const hits = subs.filter(s => { const k = norm(s); return k.length >= 5 && n.length >= 5 && (n.startsWith(k + ' ') || k.startsWith(n + ' ')); });
  return hits.length === 1 ? hits[0] : null;
}

const src = parseSource(fs.readFileSync(SRC, 'utf8'));
const out = {};
let sections = 0, types = 0;
for (const [num, cat] of Object.entries(src).sort()) {
  const cid = 'CAT-' + num;
  const subs = data.PRODUCT_SUBCATEGORIES[cid] || [];
  const byNorm = new Map(subs.map(s => [norm(s), s]));
  for (const sec of Object.values(cat.sections)) {
    const runtimeName = resolve(cid, sec.name, subs, byNorm);
    if (!runtimeName || !sec.productTypes.length) continue;
    const seen = new Set();
    const pts = sec.productTypes.filter(x => { const k = norm(x); if (!k || seen.has(k)) return false; seen.add(k); return true; });
    const attrs = [...new Set(sec.attributes)].filter(a => norm(a));
    const slot = (out[cid] = out[cid] || {});
    if (slot[runtimeName]) { // two owner sections landed on one branch: merge
      const k = new Set(slot[runtimeName].productTypes.map(norm));
      pts.forEach(x => { if (!k.has(norm(x))) { k.add(norm(x)); slot[runtimeName].productTypes.push(x); } });
      attrs.forEach(a => { if (!slot[runtimeName].attributes.includes(a)) slot[runtimeName].attributes.push(a); });
    } else slot[runtimeName] = { productTypes: pts, attributes: attrs };
    sections++; types += pts.length;
  }
}
const body = '/* GENERATED by tools/build_owner_taxonomy_branches.mjs — do not edit by hand.\n'
  + ' * Source: docs/taxonomy-source/SOKOHAI-TAXONOMY-01-44-OWNER-SOURCE-2026-11-06.txt\n'
  + ` * ${sections} owner-source sections matched to existing runtime sub-categories; ${types} product-type labels.\n`
  + ' * Merged additively by shared/canonical-taxonomy-data.js (existing ids never change). */\n'
  + 'module.exports = ' + JSON.stringify(out) + ';\n';
if (process.argv.includes('--check')) {
  if (!fs.existsSync(OUT) || fs.readFileSync(OUT, 'utf8') !== body) { console.error('owner taxonomy branches are stale — run node tools/build_owner_taxonomy_branches.mjs'); process.exit(1); }
  console.log(`PASS owner taxonomy branches up to date (${sections} sections, ${types} types)`);
} else {
  fs.writeFileSync(OUT, body);
  console.log(`wrote ${path.relative(ROOT, OUT)}: ${sections} sections, ${types} product types`);
}
